"""Generate a C++ header that compiles a library's data files into the program.

The header defines `dasmig::embedded::<name>::files`, an array of
`dasmig::core::embedded_file` that `core::load_resource` reads before looking
on disk. A WebAssembly build then needs no filesystem preload.

The output is portable C++: content is written as ordinary string literals
with every byte outside printable ASCII escaped (octal, always three digits),
so the header does not depend on the source encoding (MSVC without /utf-8)
or on line endings, and it is split into chunks below MSVC's string literal
limits. CRLF in the data is written as LF, so the header is the same whatever
the checkout's line endings; the parsed content, and so the data hash, does
not change.

Usage:
  python embed.py RESOURCES_DIR --tier lite --name biodatagen \
      --output dasmig/biodatagen_data.hpp [--include core.hpp] [--chunk-bytes 16000]

Every file below RESOURCES_DIR/<tier>/ is embedded, in sorted order, under
the path "<tier>/<relative path>".
"""

import argparse
import sys
from pathlib import Path

PIECE_SOURCE_CHARS = 2000  # source characters per literal piece (MSVC: < 16380)


def normalize(data: bytes) -> bytes:
    return data.replace(b"\r\n", b"\n")


def escape_byte(b: int) -> str:
    if b == 0x5C:
        return "\\\\"
    if b == 0x22:
        return '\\"'
    if b == 0x0A:
        return "\\n"
    if b == 0x09:
        return "\\t"
    if b == 0x0D:
        return "\\r"
    if 0x20 <= b < 0x7F:
        return chr(b)
    return f"\\{b:03o}"


def escape(data: bytes) -> str:
    return "".join(escape_byte(b) for b in data)


def chunks(data: bytes, chunk_bytes: int):
    """Split into chunks of at most chunk_bytes, preferring line ends."""
    start = 0
    while start < len(data):
        end = min(start + chunk_bytes, len(data))
        if end < len(data):
            cut = data.rfind(b"\n", start, end)
            if cut >= start:
                end = cut + 1
        yield data[start:end]
        start = end


def literal_pieces(chunk: bytes):
    """Adjacent literal pieces for one chunk: one per line, long lines split
    between whole escape sequences."""
    pieces = []
    for line in chunk.splitlines(keepends=True):
        current = []
        size = 0
        for i, b in enumerate(line):
            token = escape_byte(b)
            # An octal escape followed by a digit is correct C++ but MSVC warns
            # (C4125) at /W4; end the literal there and start the next one.
            if len(token) == 4 and i + 1 < len(line) and 0x30 <= line[i + 1] <= 0x39:
                token += '" "'
            if size + len(token) > PIECE_SOURCE_CHARS:
                pieces.append("".join(current))
                current, size = [], 0
            current.append(token)
            size += len(token)
        pieces.append("".join(current))
    return pieces


def generate(resources: Path, tier: str, name: str, include: str, chunk_bytes: int) -> str:
    root = resources / tier
    if not root.is_dir():
        raise SystemExit(f"embed.py: {root} is not a directory")
    files = sorted(p for p in root.rglob("*") if p.is_file())
    if not files:
        raise SystemExit(f"embed.py: no files below {root}")

    guard = f"DASMIG_EMBEDDED_{name.upper()}_HPP"
    lines = [
        f"// Generated by dasmig-core scripts/embed.py from resources/{tier}. Do not edit.",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        f'#include "{include}"',
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        f"namespace dasmig::embedded::{name}",
        "{",
        "",
        "// clang-format off",
    ]
    entries = []
    for index, path in enumerate(files):
        rel = f"{tier}/{path.relative_to(root).as_posix()}"
        parts = list(chunks(normalize(path.read_bytes()), chunk_bytes)) or [b""]
        lines.append(f"// {rel}")
        # Each chunk gives its length, so the compiler does not compute it in
        # a constant expression (clang 18 stops at about a million steps).
        lines.append(f"inline constexpr std::array<std::string_view, {len(parts)}> file_{index}{{")
        for part in parts:
            pieces = literal_pieces(part) or [""]
            lines.append("    std::string_view{")
            for piece in pieces:
                lines.append(f'        "{piece}"')
            lines.append(f"        , {len(part)}}},")
        lines.append("};")
        lines.append("")
        entries.append(f'    core::embedded_file{{"{escape(rel.encode("utf-8"))}", file_{index}}},')
    lines.append(f"inline constexpr std::array<core::embedded_file, {len(files)}> files{{{{")
    lines.extend(entries)
    lines.append("}};")
    lines.append("// clang-format on")
    lines.append("")
    lines.append(f"}} // namespace dasmig::embedded::{name}")
    lines.append("")
    lines.append(f"#endif // {guard}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("resources", type=Path, help="the library's resources/ directory")
    parser.add_argument("--tier", default="lite", help="tier subdirectory to embed (default: lite)")
    parser.add_argument("--name", required=True, help="C++ namespace below dasmig::embedded")
    parser.add_argument("--output", type=Path, required=True, help="header to write")
    parser.add_argument("--include", default="core.hpp", help="how the header includes the core")
    parser.add_argument("--chunk-bytes", type=int, default=16000, help="bytes per chunk (default 16000)")
    args = parser.parse_args(argv)
    if not args.name.isidentifier():
        raise SystemExit("embed.py: --name must be a C++ identifier")
    text = generate(args.resources, args.tier, args.name, args.include, args.chunk_bytes)
    args.output.write_text(text, encoding="ascii", newline="\n")
    print(f"wrote {args.output} ({len(text)} bytes)")


if __name__ == "__main__":
    sys.exit(main())
